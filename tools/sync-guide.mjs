#!/usr/bin/env node
// Copies the marks and marking guide from content/writing.json into server/guide.js,
// so the marking service and the website always use the same wording.
// Run it after changing the marking guide:   node tools/sync-guide.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const w = JSON.parse(fs.readFileSync(path.join(root, 'content', 'writing.json'), 'utf8'));
const guide = { marks: w.marks, markGuide: w.markGuide };
const out = `// GENERATED by tools/sync-guide.mjs from content/writing.json. Do not edit by hand.\nexport const GUIDE = ${JSON.stringify(guide, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'server', 'guide.js'), out);
console.log('Wrote server/guide.js');
